export function chooseQuote(previous?:number,random=Math.random) {
  const skip=Number.isInteger(previous)&&previous!>=0&&previous!<readingQuotes.length;
  const index=Math.floor(random()*(readingQuotes.length-(skip?1:0)));
  return skip&&index>=previous!?index+1:index;
}
